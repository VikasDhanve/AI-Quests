import { chromium } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const browser=await chromium.launch({headless:true,executablePath:'C:/Users/yamal/AppData/Local/ms-playwright/chromium-1248/chrome-win64/chrome.exe',args:['--enable-unsafe-swiftshader','--autoplay-policy=no-user-gesture-required']});
const page=await browser.newPage({viewport:{width:1440,height:960}});
const requests=[],failures=[],errors=[],consoleErrors=[];
await page.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'||!route.request().url().startsWith('http')?route.continue():route.abort('internetdisconnected'));
page.on('request',r=>requests.push({url:r.url(),type:r.resourceType()}));
page.on('response',r=>{if(r.status()>=400)failures.push({url:r.url(),status:r.status()});});
page.on('requestfailed',r=>failures.push({url:r.url(),error:r.failure()?.errorText}));
page.on('pageerror',e=>errors.push(e.stack));
page.on('console',m=>{if(m.type()==='error')consoleErrors.push(m.text());});
await page.goto('http://127.0.0.1:4192/ai-quests/intl/en_us',{waitUntil:'domcontentloaded',timeout:20000});
await page.waitForTimeout(10000);
await page.getByRole('button',{name:'Accept mission',exact:true}).click();
await page.waitForTimeout(5000);
console.log('BODY',(await page.locator('body').innerText()).slice(0,5000));
console.log('BUTTONS',await page.getByRole('button').allTextContents());
console.log('LINKS',await page.locator('a').evaluateAll(es=>es.map(e=>({text:e.textContent,url:e.href}))));
console.log('ERRORS',JSON.stringify({failures,errors,consoleErrors}));
await page.screenshot({path:path.join(root,'reports/local-intro.png'),fullPage:true});
fs.writeFileSync(path.join(root,'reports/local-intro-network.json'),JSON.stringify({requests,failures,errors,consoleErrors},null,2));
await browser.close();